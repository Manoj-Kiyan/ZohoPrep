package Qspiders.ForLoop;

public class AtoZ {
    public static void main(String[] args) {
        for (int i = 65; i <= 90; i++) {
            System.out.print((char)i+" ");
            
        }
        System.out.println(" ");
        for (char i = 'B'; i <= 'Z'; i++) {
            System.out.println(i + " ");
            
        }
    }
}
